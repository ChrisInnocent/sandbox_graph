# BCT-15-WINDOW

def test_insufficient_samples_is_explicit_not_zeroed():
    from sandbox_bench.analysis import analyze_case
    result=analyze_case(analysis_records(resource_min_samples=3,
        resource_series=[{'seq':1,'kind':'resource_sample','t_s':1.0,'processes':[],'clock_domain':'c'}]))
