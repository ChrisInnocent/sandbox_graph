# BCT-15-INVENTORY

def _proc(tmp_path,boot='boot'):
    proc=tmp_path/'proc';(proc/'sys/kernel/random').mkdir(parents=True)
    (proc/'sys/kernel/random/boot_id').write_text(boot)
    return proc


def _wiring(tmp_path,proc,inventory):
    path=tmp_path/'inventory.json';path.write_text(json.dumps(inventory))
    return {'version':'wiring.v1','environment_ref':'env',
        'sampler':{'kind':'procfs','inventory_path':str(path),
            'inventory_sha256':hashlib.sha256(path.read_bytes()).hexdigest(),
            'proc_root':str(proc),'clock_ticks':100,'max_pending':8}}


def _resource_case():
    return scenario_case(method='B01.TEMPLATE',resources=ResourceContract(
        interval_s=1,window_s=10,max_wait_s=5,max_gap_s=2,min_samples=3,inventory_ref='inventory'))


def _base_config():
    return {'product':'agentenv','api_url':'http://localhost:12345','data_url':'http://localhost:12346',
            'source':{'kind':'template','id':'template'}}


def test_wiring_rejects_inventory_missing_required_scope(tmp_path):
    from sandbox_bench.wiring import configured_session
    proc=_proc(tmp_path)
    inventory={'environment_ref':'env','inventory_ref':'inventory','node':'node',
               'processes':[],'evidence_ref':'operator'}
    config={**_base_config(),'wiring':_wiring(tmp_path,proc,inventory)}
    with pytest.raises(ValueError):
        configured_session(_resource_case(),config,tmp_path)


def test_wiring_rejects_procfs_boot_mismatch(tmp_path):
    from sandbox_bench.wiring import configured_session
    proc=_proc(tmp_path,boot='other')
    inventory={'environment_ref':'env','inventory_ref':'inventory','node':'node','boot_id':'boot',
               'processes':[{'identity':{'environment':'env','node':'node','boot_id':'boot','pid':42,'start_ticks':7},
                             'role':'control','component':'controller'}],'evidence_ref':'operator'}
    config={**_base_config(),'wiring':_wiring(tmp_path,proc,inventory)}
    with pytest.raises(ValueError):
        configured_session(_resource_case(),config,tmp_path)
