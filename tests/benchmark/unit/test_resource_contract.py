import hashlib
import json

import pytest

from tests.benchmark.unit.test_contract_models import sample
from tests.benchmark.scenarios.test_scenarios import case as scenario_case
from sandbox_bench.contracts import CaseContract, ResourceContract


class Scenario:
    def __init__(self): self.calls=[]
    async def execute(self,index): raise AssertionError('no remote call expected')
    async def setup(self,**kwargs): return {'status':'ready'}
    async def validate(self): return {'status':'valid'}


def session(tmp_path,data=None):
    from sandbox_bench.session import BenchSession
    case=CaseContract.model_validate(data if data is not None else sample())
    config={'api_url':'http://localhost:1','data_url':'http://localhost:1','product':'kuasar'}
    return BenchSession(case,config,tmp_path,scenario=Scenario())


def analysis_records(**changes):
    base={'case_id':'case-1','operations':[],'events':[],'window':None,
          'resource_series':[],'cohorts':[],'assertions':[],'cleanup_ledger':[],'raw_refs':[]}
    base.update(changes)
    return base


# BCT-15-REQUIRED

def test_requires_resource_observation_is_method_and_metric_driven():
    assert CaseContract.model_validate(sample()).requires_resource_observation() is True
    nonresource=sample();nonresource['method_id']='B03.PAUSE'
    assert CaseContract.model_validate(nonresource).requires_resource_observation() is False
    metric=sample();metric['method_id']='B03.PAUSE';metric['declared_metrics']=['pss_bytes']
    assert CaseContract.model_validate(metric).requires_resource_observation() is True


def test_undeclared_resource_contract_records_explicit_gap(tmp_path):
    assert 'resource_observation_not_requested' in session(tmp_path).records()['resource_gaps']


def test_explicit_resource_waiver_records_no_gap(tmp_path):
    data=sample();data['resource_observation_waived']=True
    assert 'resource_observation_not_requested' not in session(tmp_path,data).records()['resource_gaps']


def test_non_resource_method_without_contract_records_no_gap(tmp_path):
    data=sample();data['method_id']='B03.PAUSE'
    assert 'resource_observation_not_requested' not in session(tmp_path,data).records()['resource_gaps']


